# Coverage check against the built collections
import os
miss = 0
for name in out:
    p = f'public/data/c/{name}.json'
    if os.path.exists(p):
        ids = [s['id'] for s in json.load(open(p))['sections']]
        m = [i for i in ids if i not in out[name]]
        if m:
            miss += len(m)
            print('missing', name, m)
